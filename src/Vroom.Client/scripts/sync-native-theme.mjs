import { color, style } from '@react-spectrum/s2/style';
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// Native launch surfaces cannot consume CSS. Generate their values from the
// same installed Spectrum package; upgrading Spectrum updates these too.
const app = resolve(dirname(fileURLToPath(import.meta.url)), '../../Vroom.App');
function darkValue(value, token) {
  const rgb = value.match(/, rgb\((\d+), (\d+), (\d+)\)\)$/);
  if (!rgb) throw new Error(`Unsupported Spectrum color format: ${token}: ${value}`);
  return (
    '#' +
    rgb
      .slice(1)
      .map(v => Number(v).toString(16).padStart(2, '0'))
      .join('')
  );
}
function dark(token) {
  return darkValue(color(token), token);
}
function semanticDark(type, token) {
  let css = '';
  style.call(
    {
      addAsset(asset) {
        if (asset.type === 'css') css += asset.content;
      },
    },
    {
      '--native-color': { type, value: token },
    },
  );
  const value = css.match(/--native-color:\s*([^;]+);/)?.[1];
  if (!value) throw new Error(`Spectrum did not resolve ${type}: ${token}`);
  return darkValue(value, token);
}
// Use the same semantic tokens as theme.ts, so a Spectrum upgrade cannot
// silently give the native frame a different shade from the web workspace.
const base = semanticDark('backgroundColor', 'base'),
  layer = semanticDark('backgroundColor', 'layer-1');
const neutral = semanticDark('color', 'neutral'),
  subdued = semanticDark('color', 'neutral-subdued');
const accent = dark('accent-900');
const comment = '<!-- Generated by sync-native-theme.mjs from React Spectrum tokens. -->\n';
await writeFile(
  resolve(app, 'SpectrumTheme.props'),
  comment + `<Project><PropertyGroup><SpectrumBackground>${base}</SpectrumBackground></PropertyGroup></Project>\n`,
);
await writeFile(
  resolve(app, 'SpectrumColors.g.cs'),
  `// Generated from React Spectrum tokens. Do not edit color values.\nnamespace Vroom.App;\ninternal static class SpectrumColors\n{\n    public static Color Base => Color.FromArgb("${base}");\n    public static Color ContentNeutral => Color.FromArgb("${neutral}");\n    public static Color ContentSubdued => Color.FromArgb("${subdued}");\n}\n`,
);
await writeFile(
  resolve(app, 'Platforms/Android/Resources/values/colors.xml'),
  comment +
    `<resources><color name="colorPrimary">${layer}</color><color name="colorPrimaryDark">${base}</color><color name="colorAccent">${accent}</color></resources>\n`,
);
console.log('Native launch colors generated from Spectrum tokens.');
