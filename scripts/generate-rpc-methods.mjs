#!/usr/bin/env node
// Generates the client's RpcMethod type from the host dispatchers so a misspelled or removed RPC
// fails type checking. Usage: node scripts/generate-rpc-methods.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const core = path.join(root, 'src', 'Vroom.Core');
const target = path.join(root, 'src', 'Vroom.Client', 'src', 'rpc-methods.ts');
const sources = [];
const walk = dir => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!['bin', 'obj'].includes(entry.name)) walk(p);
    } else if (entry.name.endsWith('.cs')) sources.push(fs.readFileSync(p, 'utf8'));
  }
};
walk(core);
const methods = new Set();
const add = (pattern, text) => {
  for (const match of text.matchAll(pattern)) methods.add(match[1]);
};
for (const text of sources) {
  add(/case "([a-z][a-zA-Z0-9.-]+)":/g, text);
  add(/"([a-z][a-zA-Z0-9-]*\.[a-zA-Z0-9.-]+)" =>/g, text);
  add(/method == "([a-z][a-zA-Z0-9.-]+)"/g, text);
}
const rpc = fs.readFileSync(path.join(core, 'Tagging', 'TagRpc.cs'), 'utf8');
const block = rpc.match(/public static readonly string\[\] Methods =\s*\[([\s\S]*?)\];/);
if (!block) throw new Error('TagRpc.Methods not found');
for (const match of block[1].matchAll(/"([a-z][a-zA-Z0-9.-]+)"/g)) methods.add(match[1]);
const sorted = [...methods].filter(m => m.includes('.') || m === 'bootstrap').sort();
const content =
  '// Generated by scripts/generate-rpc-methods.mjs from the host dispatchers. Do not edit.\n' +
  'export type RpcMethod =\n' +
  sorted.map(m => `  | '${m}'`).join('\n') +
  ';\n';
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== content) {
    console.error('rpc-methods.ts is out of date; run node scripts/generate-rpc-methods.mjs');
    process.exit(1);
  }
} else fs.writeFileSync(target, content);
console.log(`${sorted.length} RPC methods`);
